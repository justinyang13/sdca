export function seedPrograms(db, log, skipped) {
  let count = 0;
  for (const p of PROGRAMS) {
    db.prepare(`
      INSERT INTO programs (slug, name_en, name_zh, grades_en, grades_zh,
                            description_en, description_zh, schedule_en, schedule_zh,
                            tuition_en, tuition_zh, sort, image)
      VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
      ON CONFLICT(slug) DO UPDATE SET
        name_en=excluded.name_en, name_zh=excluded.name_zh,
        grades_en=excluded.grades_en, grades_zh=excluded.grades_zh,
        description_en=excluded.description_en, description_zh=excluded.description_zh,
        schedule_en=excluded.schedule_en, schedule_zh=excluded.schedule_zh,
        tuition_en=excluded.tuition_en, tuition_zh=excluded.tuition_zh,
        sort=excluded.sort, image=excluded.image, updated_at=datetime('now')
    `).run(p.slug, p.name_en, p.name_zh, p.grades_en, p.grades_zh,
           p.description_en, p.description_zh, p.schedule_en, p.schedule_zh,
           p.tuition_en, p.tuition_zh, p.sort, p.image);
    count++;
  }
  log.push(`programs: ${count} rows`);
  return count;
}
