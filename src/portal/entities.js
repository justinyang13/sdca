export const entityActions = (e) => (e.readOnly ? ['list', 'view', 'export'] : ACTIONS);

/** Every permission code for the entity-driven pages. */
export function entityPermissions() {
  const out = [];
  for (const e of Object.values(ENTITIES)) for (const a of entityActions(e)) out.push({ code: `${e.perm}.${a}`, resource: e.perm, action: a, description: `${a} ${e.label.en}` });
  return out;
}

